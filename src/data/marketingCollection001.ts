export function buildCollection001MasterTemplates(
  adaptFn: (source: CanvasDesign, targetFormat: MarketingFormatSpec) => CanvasDesign,
): MarketingMasterTemplate[] {
  return COLLECTION_001_SPECS.map(spec => ({
    id: spec.id,
    title: spec.title,
    categoryArea: spec.categoryArea,
    topic: spec.topic,
    contentType: spec.contentType,
    targetAudience: spec.targetAudience,
    pillarId: spec.pillarId,
    pillarName: spec.pillarName,
    seriesName: MARKETING_COLLECTION_001_NAME,
    platform: spec.platform,
    formatId: spec.formatId,
    description: `${spec.chapter} · ${spec.compositionArchetype}. ${spec.conceptSummary}`,
    defaultCaption: spec.defaultCaption,
    defaultCallToAction: spec.defaultCallToAction,
    defaultHashtags: spec.defaultHashtags,
    buildDesign: (format: MarketingFormatSpec) => {
      const portraitDesign = spec.buildPortraitMaster(DEFAULT_IG_PORTRAIT);
      if (
        format.id === 'ig-feed-portrait' ||
        (format.width === 1080 && format.height === 1350 && format.safeAreaTopPct <= 8)
      ) {
        return {
          ...portraitDesign,
          id: `${spec.id}-${format.id}-${Date.now()}`,
          aspectRatio: format.canvasAspectRatio,
        };
      }
      return adaptFn(portraitDesign, format);
    },
  }));
}
