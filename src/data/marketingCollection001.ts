function makeLogoSeal(
  id: string,
  x: number,
  y: number,
  widthPct: number,
  format: MarketingFormatSpec,
  withObsidianPad = false,
  zIndex = 20,
): CanvasElement[] {
  const ratio = format.width / Math.max(1, format.height);
  const hPct = Math.round(widthPct * ratio * 10) / 10;
  const elements: CanvasElement[] = [];

  if (withObsidianPad) {
    elements.push({
      id: `${id}-logo-pad`,
      type: 'shape',
      name: 'Logo Clear-Space Obsidian Seal Pad',
      shapeType: 'rectangle',
      x,
      y,
      width: widthPct + 2.6,
      height: Math.round((widthPct + 2.6) * ratio * 10) / 10,
      rotation: 0,
      opacity: 1,
      zIndex,
      visible: true,
      fillColor: '#080808',
      borderColor: '#FF1E1E',
      borderWidth: 1,
    });
  }

  elements.push({
    id: `${id}-logo`,
    type: 'image',
    name: 'KeedoHub Official Red-K Logo',
    x,
    y,
    width: widthPct,
    height: hPct,
    rotation: 0,
    opacity: 0.98,
    zIndex: zIndex + 1,
    visible: true,
    src: keedohubLogoTransparent,
    objectFit: 'contain',
    filter: 'none',
  });

  return elements;
}

function wrapDesign(params: {
  id: string;
  name: string;
  format: MarketingFormatSpec;
  category: string;
  bgColor: string;
  bgTheme: CanvasDesign['backgroundTheme'];
  textureOverlay?: CanvasDesign['textureOverlay'];
  textureOpacity?: number;
  elements: CanvasElement[];
}): CanvasDesign {
  const now = new Date().toISOString();
  return {
    id: `${params.id}-${params.format.id}`,
    workspaceId: 'keedohub-brand-room',
    name: params.name,
    aspectRatio: params.format.canvasAspectRatio,
    width: params.format.width,
    height: params.format.height,
    backgroundColor: params.bgColor,
    backgroundTheme: params.bgTheme,
    category: params.category,
    templateFamily: MARKETING_COLLECTION_001_NAME,
    textureOverlay: params.textureOverlay || 'none',
    textureOpacity: params.textureOpacity ?? 0.28,
    createdAt: now,
    updatedAt: now,
    elements: params.elements,
  };
}

